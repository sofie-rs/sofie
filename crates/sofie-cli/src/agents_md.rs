/// Marks the file as `sofie gen`'s, so it may rewrite it.
const AGENTS_HEADER: &str = "<!-- @generated by `sofie gen`; do not edit. -->\n\n";

pub(crate) fn render_agents_md(app: &App) -> Result<(PathBuf, Option<String>), GenError> {
    let path = app.root.join("AGENTS.md");
    if read_existing(&path)?.is_some_and(|existing| !existing.starts_with(AGENTS_HEADER)) {
        return Ok((path, None));
    }
    let sections = [
        format!(
            "# Working on `{}`\n\nWritten by `sofie gen` from the code; `sofie check` reports it \
             stale when the code changes. Ask `sofie explain NAME` before reading files.\n",
            app.app.package
        ),
        modules(app),
        areas(app),
        commands(),
        APP_TOOLS.to_owned(),
        PLACES.to_owned(),
        RULES.to_owned(),
        RECIPES.to_owned(),
        DATA.to_owned(),
    ]
    .join("\n");
    Ok((path, Some(format!("{AGENTS_HEADER}{sections}"))))
}

fn modules(app: &App) -> String {
    let modules = sorted::modules(app);
    let mut text = "## Modules\n\n".to_owned();
    if modules.is_empty() {
        text.push_str("None yet; add one with `sofie new module NAME`.\n");
    }
    for module in modules {
        let _ = writeln!(text, "{}", module_line(&app.root, module));
    }
    text
}

fn module_line(root: &Path, module: &Module) -> String {
    let path = module
        .krate
        .path
        .strip_prefix(root)
        .unwrap_or(&module.krate.path);
    let tier = module
        .manifest
        .as_ref()
        .map_or("no tier", |manifest| manifest.tier.name());
    let mut parts = vec![format!(
        "- `{}` ({tier}) in `{}/`",
        module.krate.package,
        path.display()
    )];
    let areas: Vec<&str> = module.areas.iter().map(|area| area.area.as_str()).collect();
    parts.extend(listed("areas", &areas));
    let aggregates: Vec<&str> = module
        .code
        .aggregates
        .iter()
        .map(|aggregate| aggregate.name.as_str())
        .collect();
    parts.extend(listed("aggregates", &aggregates));
    let events: Vec<&str> = module.events.iter().map(String::as_str).collect();
    parts.extend(listed("events", &events));
    let tasks: Vec<String> = module
        .tasks
        .iter()
        .map(|task| task_name(module, &task.function))
        .collect();
    let tasks: Vec<&str> = tasks.iter().map(String::as_str).collect();
    parts.extend(listed("tasks", &tasks));
    if let Some(contract) = &module.contract {
        parts.push(format!("contract `{}`", contract.package));
    }
    parts.join("; ")
}

fn commands() -> String {
    let new: Vec<String> = NEW_COMMANDS
        .iter()
        .map(|command| format!("`{}`", command.invocation()))
        .collect();
    format!(
        "{COMMANDS_BEFORE_NEW}- {}: stubs in their place, then `sofie gen` and `sofie check`.\n\
         {COMMANDS_AFTER_NEW}",
        new.join(", ")
    )
}

fn listed(label: &str, names: &[&str]) -> Option<String> {
    if names.is_empty() {
        return None;
    }
    let quoted: Vec<String> = names.iter().map(|name| format!("`{name}`")).collect();
    Some(format!("{label} {}", quoted.join(", ")))
}

fn areas(app: &App) -> String {
    let mut text = "## Areas\n\n".to_owned();
    for area in app.areas() {
        let owner = area
            .contract
            .map_or("the framework".to_owned(), |contract| {
                format!("`{contract}`")
            });
        let prefix = match area.prefix() {
            Some("") => "at the root".to_owned(),
            Some(prefix) => format!("under `{prefix}`"),
            None => "under a prefix that is not a literal".to_owned(),
        };
        let client = match area.definition.map(|definition| definition.client) {
            Some(sofie_model::AreaClient::Svelte) => {
                "; its screens are compiled into Svelte components (`explain` and `components` \
                 hold for them too; markup, forms and actions behave as in HTML areas)"
            }
            Some(sofie_model::AreaClient::React) => "; it names React, which the build refuses",
            _ => "",
        };
        let _ = writeln!(
            text,
            "- `{}`: {prefix}, defined by {owner}{client}",
            area.name
        );
    }
    let _ = writeln!(text, "\n{GENERATOR_PATHS}");
    text
}

