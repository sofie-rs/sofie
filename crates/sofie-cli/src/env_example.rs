pub(crate) fn framework_keys(app: &App) -> Vec<ConfigKey> {
    let mut keys: Vec<ConfigKey> = FRAMEWORK_KEYS
        .iter()
        .map(|&(name, kind, doc)| ConfigKey {
            secret: FRAMEWORK_SECRETS.contains(&name),
            ..key(
                name.to_owned(),
                doc.to_owned(),
                kind,
                FRAMEWORK_REQUIRED.contains(&name)
                    || (name == ENVIRONMENT && app.has_feature_flags()),
            )
        })
        .collect();
    if app.modules.iter().any(|module| !module.mails.is_empty()) {
        keys.extend(
            MAIL_KEYS
                .iter()
                .map(|&(name, kind, required, doc)| ConfigKey {
                    secret: MAIL_SECRETS.contains(&name),
                    ..key(name.to_owned(), doc.to_owned(), kind, required)
                }),
        );
    }
    if uses_oauth(app) {
        keys.extend(
            OAUTH_KEYS
                .iter()
                .map(|&(name, doc)| key(name.to_owned(), doc.to_owned(), KeyKind::Text, false)),
        );
    }
    if app.depends_on(sofie_model::naming::CONTENT_PACKAGE) {
        keys.push(key(
            CONTENT_BASE_URL.to_owned(),
            "Where the app is reached, such as `https://example.com`: pages' canonical URLs and the sitemap name it."
                .to_owned(),
            KeyKind::Text,
            true,
        ));
    }
    keys
}

fn uses_oauth(app: &App) -> bool {
    app.identity.as_ref().is_some_and(|identity| {
        identity
            .routes
            .iter()
            .any(|route| route.handler == OAUTH_HANDLER)
    })
}

fn key(name: String, doc: String, kind: KeyKind, required: bool) -> ConfigKey {
    ConfigKey {
        doc: vec![doc],
        kind,
        required,
        fallback: BASE_URL_OVERRIDES
            .contains(&name.as_str())
            .then(|| BASE_URL.to_owned()),
        name,
        secret: false,
    }
}

/// `sofie::remote::connect` reads a split module's keys as a vendor's, under this prefix.
pub(crate) fn remote_prefix(module: &str) -> String {
    format!("{}_REMOTE", module.to_ascii_uppercase())
}

pub(crate) fn remote_keys(module: &str) -> Vec<ConfigKey> {
    let prefix = remote_prefix(module);
    VENDOR_KEYS
        .iter()
        .map(|&(name, doc, kind)| {
            let base_url = name == "BASE_URL";
            let doc = if base_url {
                format!("Where the app module `{module}` was split into answers, such as `http://{module}.internal`.")
            } else {
                doc.to_owned()
            };
            key(format!("{prefix}_{name}"), doc, kind, base_url)
        })
        .collect()
}

fn gateway_keys(module: &Module) -> Vec<ConfigKey> {
    let prefix = module.krate.crate_name.to_ascii_uppercase();
    let mut keys = Vec::new();
    for gateway in &module.gateways {
        let vendors: Vec<_> = gateway
            .adapters
            .iter()
            .filter_map(|adapter| Some((adapter.vendor.as_deref()?, adapter)))
            .collect();
        let only = vendors.len() == 1;
        let names: Vec<&str> = vendors.iter().map(|(vendor, _)| *vendor).collect();
        let trait_name = gateway.path.last().map_or("", String::as_str);
        let doc = if only {
            format!("The vendor `{trait_name}` calls; {} when unset.", names[0])
        } else {
            format!("The vendor `{trait_name}` calls: {}.", names.join(", "))
        };
        keys.push(key(
            format!("{prefix}_{}", gateway.name.to_ascii_uppercase()),
            doc,
            KeyKind::Text,
            !only,
        ));
        for (vendor, adapter) in vendors {
            let vendor_prefix = vendor_prefix(module, vendor);
            keys.extend(VENDOR_KEYS.iter().map(|&(name, doc, kind)| {
                key(
                    format!("{vendor_prefix}_{name}"),
                    doc.to_owned(),
                    kind,
                    false,
                )
            }));
            keys.extend(adapter.settings.iter().map(|key| ConfigKey {
                required: key.required && only,
                ..key.clone()
            }));
        }
    }
    keys
}

pub(crate) fn vendor_prefix(module: &Module, vendor: &str) -> String {
    format!("{}_{}", module.krate.crate_name, vendor).to_ascii_uppercase()
}

pub(crate) fn module_keys(module: &Module) -> Vec<ConfigKey> {
    let config = module
        .config
        .iter()
        .flat_map(|config| config.keys.iter().cloned());
    config.chain(gateway_keys(module)).collect()
}

/// A `.env.example` written by hand is the developer's, as a hand-written
/// `AGENTS.md` is: `None` leaves it alone.
pub(crate) fn render_env_examples(app: &App) -> Result<Vec<(PathBuf, Option<String>)>, GenError> {
    rendered_env_examples(app)
        .into_iter()
        .map(|(path, text)| {
            let hand_written =
                read_existing(&path)?.is_some_and(|existing| !existing.starts_with(ENV_HEADER));
            Ok((path, text.filter(|_| !hand_written)))
        })
        .collect()
}

fn rendered_env_examples(app: &App) -> Vec<(PathBuf, Option<String>)> {
    let mut files = Vec::new();
    let mut sections = vec![format!(
        "# The framework\n\n{}",
        entries(&framework_keys(app))
    )];
    for module in &app.modules {
        let keys = module_keys(module);
        let reads_keys = module.config.is_some() || !keys.is_empty();
        let example = reads_keys.then(|| entries(&keys));
        if let Some(example) = &example {
            let name = &module.krate.crate_name;
            sections.push(format!("# Module {name}\n\n{example}"));
        }
        let file = module.krate.path.join(".env.example");
        files.push((
            file,
            example.map(|example| format!("{ENV_HEADER}\n{example}")),
        ));
    }
    sections.extend(app.split.remote.iter().map(|remote| {
        let keys = entries(&remote_keys(&remote.name));
        format!("# Module {} in another app\n\n{keys}", remote.name)
    }));
    let text = format!("{ENV_HEADER}\n{}", sections.join("\n"));
    files.push((app.root.join(".env.example"), Some(text)));
    files
}

fn entries(keys: &[ConfigKey]) -> String {
    keys.iter().map(entry).collect::<Vec<_>>().join("\n")
}

fn entry(key: &ConfigKey) -> String {
    let mut lines: Vec<String> = key.doc.iter().map(|line| format!("# {line}")).collect();
    lines.extend(
        key.fallback
            .iter()
            .map(|fallback| format!("# {fallback} when unset.")),
    );
    let comment = if key.required && key.fallback.is_none() {
        ""
    } else {
        "# "
    };
    lines.push(format!("{comment}{}=\n", key.name));
    lines.join("\n")
}

