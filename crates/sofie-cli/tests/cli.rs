#[test]
fn gen_writes_route_builders_and_member_areas_into_the_contract_until_written_by_hand() {
    let fixture = Fixture::new();
    fixture.write(
        "Cargo.toml",
        "[workspace]\nresolver = \"3\"\nmembers = [\"app\", \"modules/*\", \"modules/*/contract\"]\n",
    );
    fixture.write(
        "app/Cargo.toml",
        &manifest(
            "shop",
            "order = { path = \"../modules/order\" }\norder-contract = { path = \"../modules/order/contract\" }\n",
        ),
    );
    fixture.write(
        "modules/order/contract/Cargo.toml",
        &manifest("order-contract", ""),
    );
    fixture.write(
        "modules/order/contract/src/lib.rs",
        "pub mod area;\nmod r#gen;\npub use r#gen::routes;\n",
    );
    fixture.write("modules/order/contract/src/area.rs", MEMBER);
    fixture.write(
        "modules/order/src/areas/member/routes.rs",
        "pub fn routes(routes: &mut Routes<Member>) {\n    routes.screen(\"/orders\", \"orders\", queries::list_orders);\n}\n",
    );
    fixture.write(
        "modules/order/src/areas/member/screens/orders.html",
        "<Section title=\"Orders\"></Section>\n",
    );
    fixture.write(
        "modules/order/src/lib.rs",
        "mod actions;\npub mod module;\nmod queries;\npub mod areas {\n    pub mod member {\n        pub mod routes;\n    }\n}\n",
    );
    fs::remove_dir_all(fixture.directory.path("modules/order/src/areas/web")).unwrap();

    let written = fixture.sofie(&["gen"]);
    assert_eq!(
        written.status.code(),
        Some(0),
        "{}",
        String::from_utf8_lossy(&written.stderr)
    );
    let generated = fixture.read("modules/order/contract/src/gen/mod.rs");
    fixture.write(
        "modules/order/contract/src/area.rs",
        &format!("{MEMBER}\nimpl sofie_identity::MemberArea for Member {{\n    const HOME: &'static str = \"/\";\n}}\n"),
    );
    let stale = fixture.sofie(&["gen", "--check"]);
    fixture.sofie(&["gen"]);
    let rewritten = fixture.read("modules/order/contract/src/gen/mod.rs");

    assert!(
        generated.contains("impl sofie_identity::MemberArea for crate::area::Member {\n    const HOME: &'static str = \"/account/orders\";\n}\n"),
        "{generated}"
    );
    assert!(
        generated.contains("pub fn list_orders() -> sofie::http::RoutePath {\n            sofie::http::RoutePath::new(sofie::http::Method::GET, \"/account/orders\".to_owned())"),
        "{generated}"
    );
    assert_eq!(stale.status.code(), Some(1));
    assert!(String::from_utf8_lossy(&stale.stderr).contains("mod.rs: stale"));
    assert!(!rewritten.contains("MemberArea"), "{rewritten}");
    assert!(rewritten.contains("pub mod routes"), "{rewritten}");

    let routes = stdout(&fixture.sofie(&["routes"]));
    let explained = stdout(&fixture.sofie(&["explain", "order.member.list_orders"]));
    let unknown = fixture.sofie(&["explain", "nothing"]);

    assert!(
        routes
            .lines()
            .nth(1)
            .is_some_and(|row| row.split_whitespace().collect::<Vec<_>>()
                == [
                    "member",
                    "GET",
                    "/account/orders",
                    "order.member.list_orders",
                    "order::queries::list_orders",
                    "principal's",
                    "own",
                    "screen(orders)"
                ]),
        "{routes}"
    );
    assert!(
        explained
            .starts_with("route order.member.list_orders\n  area: member\n  GET /account/orders\n"),
        "{explained}"
    );
    assert_eq!(unknown.status.code(), Some(1));
}

