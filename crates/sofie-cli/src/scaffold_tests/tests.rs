/// A product created only through a `Permitted` area's route, with a hand-written factory.
fn app_creating_behind_a_permission(signs_members_in: bool) -> TemporaryDirectory {
    let app = app_with_a_product_page();
    let identity = if signs_members_in {
        app.write("sofie-identity/Cargo.toml", &manifest("sofie-identity", ""));
        app.write("sofie-identity/src/lib.rs", "");
        app.write(
            "Cargo.toml",
            "[workspace]\nresolver = \"3\"\nmembers = [\"app\", \"modules/*\", \"modules/*/contract\", \"sofie-identity\"]\n",
        );
        "sofie-identity = { path = \"../sofie-identity\" }\n"
    } else {
        ""
    };
    app.write(
        "app/Cargo.toml",
        &manifest(
            "shop",
            &format!(
                "catalog = {{ path = \"../modules/catalog\" }}\n\
                 catalog-contract = {{ path = \"../modules/catalog/contract\" }}\n{identity}"
            ),
        ),
    );
    app.write(
        "modules/catalog/contract/src/lib.rs",
        "pub mod area;\nmod r#gen;\n\npub use r#gen::routes;\n",
    );
    app.write(
        "modules/catalog/contract/src/area.rs",
        "pub struct Staff;\n\nimpl Area for Staff {\n    const NAME: &'static str = \"staff\";\n    \
         const PREFIX: &'static str = \"/staff\";\n    const SIGN_IN: &'static str = \"/staff/sign-in\";\n    \
         type Principal = sofie_identity::Permitted;\n}\n",
    );
    app.write(
        "modules/catalog/src/lib.rs",
        "mod actions;\nmod product;\n\npub use product::{Product, ProductStatus};\n\n\
         pub mod areas {\n    pub mod staff {\n        pub mod routes;\n    }\n}\n",
    );
    app.write(
        "modules/catalog/src/actions.rs",
        "use sofie::prelude::*;\n\nuse crate::Product;\n\n\
         pub async fn add_product() -> Result<Product> {\n    todo!()\n}\n",
    );
    app.write(
        "modules/catalog/src/areas/staff/routes.rs",
        "use sofie::prelude::*;\n\nuse crate::actions;\n\npub fn routes(routes: &mut Routes<catalog_contract::area::Staff>) {\n    \
         routes.post(\"/products\", actions::add_product);\n}\n",
    );
    app.write(
        "modules/catalog/src/product/factory.rs",
        "use sofie::prelude::*;\n",
    );

    app
}

