    assert!(!text.contains("habit_is_made_by_its_factory"), "{text}");
    assert!(!text.contains("habit_name_keeps"), "{text}");
    assert!(
        written
            .uncovered
            .iter()
            .all(|gap| !gap.contains("HabitName")),
        "{written:?}"
    );
