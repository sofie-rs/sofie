const ROUTES: &str = "use sofie::prelude::*;

pub fn routes(routes: &mut Routes<Web>) {
    routes.get(\"/orders\", queries::list_orders);
    routes.post(\"/orders\", actions::place_order);
}
";

struct Fixture {
    directory: TemporaryDirectory,
}

impl Fixture {
    fn new() -> Self {
        let fixture = Self {
            directory: TemporaryDirectory::new("sofie-cli"),
        };
        fixture.write(
            "Cargo.toml",
            "[workspace]\nresolver = \"3\"\nmembers = [\"app\", \"modules/*\"]\n",
        );
        fixture.write(
            "app/Cargo.toml",
            &manifest("shop", "order = { path = \"../modules/order\" }\n"),
        );
        fixture.write(
            "app/src/main.rs",
            "mod wiring;\n\nfn main() {\n    let _ = (wiring::MODULES, wiring::app, wiring::worker);\n}\n",
        );
        fixture.write("modules/order/Cargo.toml", &manifest("order", ""));
        fixture.write(
            "modules/order/src/lib.rs",
            "mod actions;\npub mod module;\nmod queries;\nmod wiring;\nmod areas {\n    pub mod web {\n        pub mod routes;\n    }\n}\n",
        );
        fixture.write(
            "modules/order/src/module.rs",
            "pub const MODULE: sofie::Module = sofie::Module {\n    name: \"order\",\n    tier: sofie::Tier::Core,\n    context: None,\n    settings: &[],\n    ..crate::wiring::GENERATED\n};\n",
        );
        fixture.write("modules/order/src/actions.rs", "");
        fixture.write("modules/order/src/queries.rs", "");
        fixture.write("modules/order/migrations/0001_create_order.sql", "");
        fixture.write("modules/order/src/areas/web/routes.rs", ROUTES);
        fixture
    }

    fn write(&self, relative: &str, text: &str) {
        self.directory.write(relative, text);
    }

    fn read(&self, relative: &str) -> String {
        fs::read_to_string(self.directory.path(relative)).unwrap()
    }

    fn sofie(&self, arguments: &[&str]) -> Output {
        Command::new(env!("CARGO_BIN_EXE_sofie"))
            .args(arguments)
            .arg(self.directory.root())
            .output()
            .unwrap()
    }
}

fn stdout(output: &Output) -> String {
    String::from_utf8(output.stdout.clone()).unwrap()
}

