#[test]
fn dead_code_is_a_finding_unless_allowed_and_a_stale_allowance_is_reported() {
    let fixture = Fixture::new();
    fixture.write("helper/Cargo.toml", &manifest("helper", ""));
    fixture.write("helper/src/lib.rs", "");
    fixture.write(
        "modules/order/Cargo.toml",
        &manifest("order", "helper = { path = \"../../helper\" }\n"),
    );
    fixture.write("modules/order/src/actions.rs", "pub fn forgotten() {}\n");
    assert_eq!(fixture.sofie(&["gen"]).status.code(), Some(0));

    let dead = stdout(&fixture.sofie(&["check"]));
    fixture.write(
        "dead-code-allow.toml",
        "[[item]]\npackage = \"order\"\nname = \"forgotten\"\nreason = \"kept for a test\"\n\n\
         [[dependency]]\npackage = \"order\"\nname = \"helper\"\nreason = \"kept for a test\"\n\n\
         [[item]]\npackage = \"order\"\nname = \"routes\"\nreason = \"it is used\"\n",
    );
    let allowed = stdout(&fixture.sofie(&["check"]));

    for expected in [
        "error[unused-item]: `forgotten` is `pub` but nothing names it outside its definition",
        "\n  --> modules/order/src/actions.rs:1\n",
        "error[unused-dependency]: `helper` is in [dependencies] but no source of `order` names `helper`",
        "\n  --> modules/order/Cargo.toml:7\n",
    ] {
        assert!(dead.contains(expected), "missing {expected} in {dead}");
    }
    // Two `pub` items are too few for a share: the ceiling allows one from 50.
    assert!(dead.ends_with("\n2 problems\n"), "{dead}");
    assert!(!allowed.contains("error[unused-ratio]"), "{allowed}");
    assert!(
        allowed.contains("error[stale-allowance]: `routes` of `order` is allowed as unused"),
        "{allowed}"
    );
    assert!(allowed.ends_with("\n1 problem\n"), "{allowed}");
}

