/// Without the spaces and trailing commas rustfmt places by line length.
pub(super) fn has(wiring: &str, expected: &str) -> bool {
    let compact = |text: &str| {
        let joined: String = text.split_whitespace().collect();
        joined
            .replace(",)", ")")
            .replace(",]", "]")
            .replace(",}", "}")
            .replace(",>", ">")
    };
    compact(wiring).contains(&compact(expected))
}

pub(super) fn formatted(app: &App) -> String {
    with_forms(app, &[])
}

/// The `order` module's own wiring.
fn module_formatted(app: &App) -> String {
    let order = app
        .modules
        .iter()
        .find(|module| module.krate.crate_name == "order")
        .unwrap();
    format_rust(
        &render_module_wiring(app, order),
        std::path::Path::new("generated.rs"),
    )
    .unwrap()
}

fn with_forms(app: &App, forms: &[crate::forms::DescribedForm]) -> String {
    format_rust(
        &render_wiring(app, None, forms),
        std::path::Path::new("generated.rs"),
    )
    .unwrap()
}

