    let fixture = with_config();
    fixture.write(
        ".env.production",
        "# production\nDATABASE_URL=postgres://db/shop\nSOFIE_MIGRATE=yes\nORDER_WINDOW_HOURS=\"-2\"\n",
    );

    let check = fixture.sofie(&["config", "check", "--env", "production"]);

    let text = stdout(&check);
    assert_eq!(check.status.code(), Some(1), "{text}");
    for expected in [
        "error[config]: SOFIE_SIGNING_KEYS is not set, and the app cannot start without it\n  --> .env.production:1\n",
        "error[config]: ORDER_INVOICE_PREFIX is not set, and the app cannot start without it\n  --> .env.production:1\n   = help: add `ORDER_INVOICE_PREFIX=…`: Printed before every invoice number.\n",
        "error[config]: SOFIE_MIGRATE is not `on` or `off`\n  --> .env.production:3\n",
        "error[config]: ORDER_WINDOW_HOURS is not a whole number of 0 or more\n  --> .env.production:4\n",
    ] {
        assert!(text.contains(expected), "missing {expected} in {text}");
    }
    assert!(text.ends_with("\n4 problems\n"), "{text}");
